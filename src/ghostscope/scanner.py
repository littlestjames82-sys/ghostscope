"""Project scanner: .gitignore-aware walk, language/test/detect flags.

Mirrors the semantics GhostSlice's scanner exposes for the fields
GhostScope consumes (path, language, is_test, is_lockfile,
generated/minified/vendored detection), implemented with stdlib
only so GhostScope runs standalone. Binary files are skipped.
"""
from __future__ import annotations

import fnmatch
import os
from dataclasses import dataclass, field
from pathlib import Path

from .tokens import estimate_tokens, looks_minified

LANGUAGE_BY_EXT = {
    ".py": "python",
    ".ts": "typescript", ".tsx": "typescript",
    ".js": "javascript", ".jsx": "javascript",
    ".mjs": "javascript", ".cjs": "javascript",
    ".md": "markdown", ".markdown": "markdown", ".txt": "text",
    ".json": "json",
    ".go": "go", ".rs": "rust", ".java": "java", ".cs": "csharp",
    ".php": "php", ".rb": "ruby", ".kt": "kotlin", ".kts": "kotlin",
    ".swift": "swift",
    ".c": "c", ".h": "c",
    ".cpp": "cpp", ".cc": "cpp", ".cxx": "cpp", ".hpp": "cpp", ".hh": "cpp",
    ".scala": "scala", ".sc": "scala",
    ".yaml": "yaml", ".yml": "yaml", ".toml": "toml",
    ".sql": "sql", ".sh": "shell", ".bash": "shell", ".zsh": "shell",
    ".ps1": "powershell", ".psm1": "powershell",
    ".ipynb": "notebook",
}

BINARY_EXTS = {
    ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".pdf", ".zip",
    ".gz", ".tar", ".bz2", ".xz", ".7z", ".exe", ".dll", ".so", ".dylib",
    ".o", ".a", ".class", ".jar", ".wasm", ".mp3", ".mp4", ".mov",
    ".woff", ".woff2", ".ttf", ".pyc", ".bin",
}

LOCKFILES = {
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "Pipfile.lock",
    "poetry.lock", "Cargo.lock", "composer.lock", "Gemfile.lock",
    "go.sum", "uv.lock",
}

DEFAULT_IGNORE_DIRS = {
    ".git", ".hg", ".svn", "node_modules", "dist", "build", "__pycache__",
    ".venv", "venv", ".tox", ".mypy_cache", ".pytest_cache", ".idea",
    ".vscode", "target", ".next", ".nuxt", "coverage", ".ghostscope-cache",
}

_GENERATED_MARKERS = ("@generated", "code generated by", "generated by",
                      "do not edit", "auto-generated", "autogenerated")
_VENDORED_DIRS = {"vendor", "vendored", "third_party", "thirdparty"}


def language_for(path: str) -> str:
    return LANGUAGE_BY_EXT.get(Path(path).suffix.lower(), "text")


def is_test_file(rel: str) -> bool:
    p = Path(rel)
    name = p.name.lower()
    parts = [part.lower() for part in p.parts]
    if any(part in ("tests", "test", "__tests__", "spec", "specs")
           for part in parts[:-1]):
        return True
    if name.startswith("test_") or name.endswith("_test.py") \
            or name.endswith("_test.go") or name.endswith(".test.ts") \
            or name.endswith(".test.tsx") or name.endswith(".test.js") \
            or name.endswith(".test.jsx") or ".spec." in name \
            or name.startswith("test.") or name.endswith("_spec.rb") \
            or name.endswith("_test.rb") or name.endswith("test.java") \
            or name.endswith("tests.java") or name.endswith("test.cs") \
            or name.endswith("tests.cs"):
        return True
    return name in ("conftest.py",)


def is_lockfile(rel: str) -> bool:
    return Path(rel).name in LOCKFILES


@dataclass
class FileEntry:
    path: str
    abspath: str
    size: int
    lines: int
    tokens: int
    language: str
    is_test: bool = False
    is_lockfile: bool = False
    is_generated: bool = False
    is_minified: bool = False
    is_vendored: bool = False
    detect_evidence: dict = field(default_factory=dict)


@dataclass
class ScanResult:
    root: str
    files: list[FileEntry] = field(default_factory=list)

    @property
    def total_tokens(self) -> int:
        return sum(f.tokens for f in self.files)

    def by_path(self) -> dict[str, FileEntry]:
        return {f.path: f for f in self.files}


def read_text(path: str | Path) -> str:
    data = Path(path).read_bytes()
    if data.startswith(b"\xef\xbb\xbf"):
        return data.decode("utf-8-sig", errors="replace")
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        return data.decode("utf-16", errors="replace")
    return data.decode("utf-8", errors="replace")


def _gitignore_patterns(root: Path) -> list[str]:
    pats: list[str] = []
    gi = root / ".gitignore"
    if gi.is_file():
        try:
            for line in gi.read_text(encoding="utf-8", errors="replace").splitlines():
                line = line.strip()
                if line and not line.startswith("#"):
                    pats.append(line)
        except OSError:
            pass
    return pats


def _ignored(rel: str, patterns: list[str]) -> bool:
    ignored = False
    parts = Path(rel).parts
    for pat in patterns:
        neg = pat.startswith("!")
        p = pat[1:] if neg else pat
        p = p.strip("/")
        if not p:
            continue
        hit = fnmatch.fnmatch(rel, p) or fnmatch.fnmatch(rel, p + "/**") \
            or any(fnmatch.fnmatch(part, p) for part in parts) \
            or fnmatch.fnmatch(Path(rel).name, p)
        if hit:
            ignored = not neg
    return ignored


def detect_flags(rel: str, text: str, language: str) -> tuple[bool, bool, bool, dict]:
    evidence: dict[str, str] = {}
    head = "\n".join(text.splitlines()[:5]).lower()
    generated = any(m in head for m in _GENERATED_MARKERS)
    if generated:
        evidence["generated"] = "header marker in first 5 lines"
    minified = language in ("javascript", "typescript") and looks_minified(text)
    if minified:
        evidence["minified"] = "long-line heuristic (see tokens.looks_minified)"
    vendored = any(part.lower() in _VENDORED_DIRS for part in Path(rel).parts[:-1])
    if vendored:
        evidence["vendored"] = "path under a vendor directory"
    return generated, minified, vendored, evidence


def scan(root: str | Path) -> ScanResult:
    root = Path(root).expanduser().resolve()
    if not root.exists():
        raise FileNotFoundError(str(root))
    result = ScanResult(root=str(root))
    if root.is_file():
        candidates = [(root, root.name)]
    else:
        patterns = _gitignore_patterns(root)
        candidates = []
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = sorted(
                d for d in dirnames if d not in DEFAULT_IGNORE_DIRS)
            for name in sorted(filenames):
                abspath = Path(dirpath) / name
                rel = abspath.relative_to(root).as_posix()
                if _ignored(rel, patterns):
                    continue
                candidates.append((abspath, rel))
    for abspath, rel in candidates:
        if abspath.suffix.lower() in BINARY_EXTS:
            continue
        try:
            data = abspath.read_bytes()
        except OSError:
            continue
        if b"\x00" in data[:8192]:
            continue
        text = read_text(abspath)
        lang = language_for(rel)
        generated, minified, vendored, evidence = detect_flags(rel, text, lang)
        result.files.append(FileEntry(
            path=rel, abspath=str(abspath), size=len(data),
            lines=text.count("\n") + (1 if text and not text.endswith("\n") else 0),
            tokens=estimate_tokens(text, lang), language=lang,
            is_test=is_test_file(rel), is_lockfile=is_lockfile(rel),
            is_generated=generated, is_minified=minified,
            is_vendored=vendored, detect_evidence=evidence,
        ))
    result.files.sort(key=lambda f: f.path)
    return result
